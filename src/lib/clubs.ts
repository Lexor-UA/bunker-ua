export const CLUBS_BY_ID: Record<string, Club> = Object.fromEntries(
  CLUBS.map((club) => [club.id, club])
);

export function getClubById(id: string | null | undefined): Club | null {
  if (!id) return null;
  return CLUBS_BY_ID[id] ?? null;
}

export function getClubsForPool(pool: ClubPoolType, minNeeded = 16): Club[] {
  if (pool === 'NONE') return [];
  if (pool === 'ELITE_5') {
    const elite = CLUBS.filter((c) => c.tier === 'ELITE_5');
    if (elite.length >= minNeeded) return elite;
    // Якщо гравців 16 або 32, доповнюємо найкращими 4.5★ клубами
    const extra = CLUBS.filter((c) => c.tier !== 'ELITE_5');
    return [...elite, ...extra];
  }
  if (pool === 'BALANCED_45') {
    const balanced = CLUBS.filter(
      (c) => c.tier === 'BALANCED_45' || c.tier === 'UPL_PRIDE'
    );
    if (balanced.length >= minNeeded) return balanced;
    return CLUBS;
  }
  return CLUBS;
}

